import {test} from 'node:test';import assert from 'node:assert/strict';
import {EditSession,generatedHeader} from '../src/edit-session.js';
import {lineChanges,decodeText} from '../src/export-diff.js';
const bytes=value=>new TextEncoder().encode(value);

test('generated protection only recognises leading comments and allows persistent overrides',()=>{
 const s=new EditSession(),file='P/ui/quest.json',content=bytes('// 由 tools/build_quest.py 生成，请勿手改\n{}');
 assert.match(generatedHeader(new TextDecoder().decode(content)),/build_quest.py/);
 assert.equal(s.protected(file,content).locked,true);
 assert.equal(s.protected(file,bytes('{"text":"automatically generated"}')).locked,false);
 assert.equal(s.protected(file,bytes('{}\n// automatically generated')).locked,false);
 assert.equal(s.protected(file,bytes('/* Auto-generated by build.js */\n{}')).locked,true);
 s.protection.set(file,false);assert.equal(s.protected(file,content).locked,false);
 const next=new EditSession();next.loadSettings(s.settings());assert.equal(next.protected(file,content).locked,false);
 next.protection.set(file,true);assert.equal(next.protected(file,bytes('{}')).locked,true);
 assert.throws(()=>next.loadSettings('{"version":1,"generatedFiles":{"../outside":true}}'));
 assert.throws(()=>next.loadSettings('{"version":1,"generatedFiles":[]}'));
});
test('baselines track fresh imports, dependency replacement and undo, excluding editor/vanilla files',()=>{
 const s=new EditSession(),original=bytes('{"offset":[1,2]}'),changed=bytes('{"offset":[2,2]}'),files=new Map([['P/ui/a.json',original]]);
 s.acceptImport(files,{replace:true});assert.equal(s.changes(files).length,0);
 const snapshot=s.snapshot();files.set('P/ui/a.json',changed);assert.equal(s.changes(files)[0].kind,'modified');
 s.acceptImport(files,{changedPaths:['P/ui/a.json']});assert.equal(s.changes(files).length,0);
 s.restore(snapshot);assert.equal(s.changes(files).length,1);
 files.set('.easysee/project.json',bytes('{}'));assert.equal(s.changes(files).length,1);
 files.set('new.json',bytes('{}'));assert.equal(s.changes(files).find(c=>c.path==='new.json').kind,'added');
 files.delete('P/ui/a.json');assert.equal(s.changes(files).find(c=>c.path==='P/ui/a.json').kind,'removed');
});
test('line diff shows only relevant context and preserves explicit line endings and BOM',()=>{
 const before='\uFEFF// schema\r\n{"offset": [1, 2]}\r\n';
 const result=lineChanges(before,before.replace('[1, 2]','[3, 2]'));
 assert.equal(result.fallback,false);assert.equal(result.rows.filter(r=>r.kind==='remove').length,1);assert.equal(result.rows.filter(r=>r.kind==='add').length,1);
 assert.equal(result.rows[0].text,'\uFEFF// schema\r\n');
 assert.equal(decodeText(bytes(before)),before);assert.equal(decodeText(Uint8Array.of(255)),null);
 assert.equal(decodeText(Uint8Array.of(0)),null);
});
